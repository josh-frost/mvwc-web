import type { Metadata } from "next";
import type { SanityImageSource } from "@sanity/image-url";
import { urlFor } from "@/sanity/lib/image";
import { DEFAULT_DESCRIPTION, SITE_NAME } from "@/lib/site";

// Matches the `seo` object type in sanity/schemaTypes/seoType.ts
export type Seo = {
  title?: string;
  description?: string;
  image?: SanityImageSource & { asset?: unknown };
};

type ImageWithAlt = SanityImageSource & { asset?: unknown; alt?: string };

// GROQ projection for an `seo` field; include in queries used by generateMetadata.
export const SEO_PROJECTION = `seo{ title, description, image }`;

const SHARE_IMAGE = { width: 1200, height: 630 };

// Generated by app/og-image.png/route.tsx
export const DEFAULT_SHARE_IMAGE = { url: "/og-image.png", ...SHARE_IMAGE, alt: SITE_NAME };

// Next replaces (doesn't merge) a parent's openGraph/twitter objects when a page sets
// its own, so every page's metadata repeats these site-wide values.
export const BASE_OPEN_GRAPH = {
  siteName: SITE_NAME,
  type: "website",
  locale: "en_US",
} as const;

function shareImage(image: ImageWithAlt | undefined, alt: string) {
  if (!image?.asset) return undefined;
  return [
    {
      url: urlFor(image).width(SHARE_IMAGE.width).height(SHARE_IMAGE.height).fit("crop").url(),
      ...SHARE_IMAGE,
      alt: image.alt || alt,
    },
  ];
}

/**
 * Builds page metadata from a page's SEO fields with fallbacks:
 * SEO title/description/image, then the page's own values, then site defaults
 * (including the default logo share image).
 */
export function pageMetadata({
  seo,
  title,
  description,
  image,
  path,
  absoluteTitle = false,
}: {
  seo?: Seo | null;
  title: string;
  description?: string | null;
  image?: ImageWithAlt | null;
  path: string;
  absoluteTitle?: boolean;
}): Metadata {
  const resolvedTitle = seo?.title || title;
  const resolvedDescription = seo?.description || description || DEFAULT_DESCRIPTION;
  const images = shareImage(seo?.image ?? image ?? undefined, resolvedTitle) ?? [DEFAULT_SHARE_IMAGE];

  return {
    title: absoluteTitle ? { absolute: resolvedTitle } : resolvedTitle,
    description: resolvedDescription,
    alternates: { canonical: path },
    openGraph: {
      ...BASE_OPEN_GRAPH,
      title: resolvedTitle,
      description: resolvedDescription,
      url: path,
      images,
    },
    twitter: {
      card: "summary_large_image",
      title: resolvedTitle,
      description: resolvedDescription,
      images,
    },
  };
}
